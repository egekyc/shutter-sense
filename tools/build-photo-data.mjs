// Turns data/photo-candidates.json (from curate-photos.mjs) into data/photos.js and sorts every
// photo into a level. tools/photo-levels.json can exclude photos or force a level by Commons page id.
// The output is a plain <script> (not JSON + fetch) so the game also runs when index.html is opened from disk.
//
// Usage:  node tools/build-photo-data.mjs

import { readFile, writeFile } from "node:fs/promises";

const read = async (p) => JSON.parse(await readFile(new URL(p, import.meta.url), "utf8"));
const candidates = await read("../data/photo-candidates.json");
// My own photos (from tools/import-my-photos.mjs), stored in images/mine/.
let mine = [];
try {
  mine = await read("../data/my-photos.json");
} catch {
  /* not imported yet */
}
const levels = await read("./photo-levels.json");
const exclude = new Set(levels.exclude);
const forced = new Map();
for (const lvl of ["beginner", "intermediate", "expert"]) for (const id of levels[lvl] ?? []) forced.set(id, lvl);

const STD_ISO = [50, 64, 80, 100, 125, 160, 200, 250, 320, 400, 500, 640, 800, 1000, 1250, 1600, 2000, 2500, 3200, 4000, 5000, 6400, 8000, 10000, 12800, 16000, 25600];
const STD_SHUTTER = [8000, 6400, 5000, 4000, 3200, 2500, 2000, 1600, 1250, 1000, 800, 640, 500, 400, 320, 250, 200, 160, 125, 100, 80, 60, 50, 40, 30, 25, 20, 15, 13, 10, 8, 6, 5, 4, 3, 2.5]
  .map((d) => 1 / d)
  .concat([0.5, 0.6, 0.8, 1, 1.3, 1.6, 2, 2.5, 3.2, 4, 5, 6, 8, 10, 13, 15, 20, 25, 30]);
// Interchangeable-lens cameras: depth-of-field clues behave the way photography lessons describe.
const SYSTEM_CAMERA = /\bEOS\b|NIKON D\d|NIKON Z|ILCE|\bSLT-|DSLR|PENTAX K|\bX100|X-T\d|X-E\d|X-Pro|X-H|E-M\d|E-P\d|DMC-G|DMC-GX|DC-G|GFX|Leica M/i;

const near = (list, v, stops = 0.12) => list.some((s) => Math.abs(Math.log2(v / s)) <= stops);

function autoLevel(p) {
  const system = p.camera && SYSTEM_CAMERA.test(p.camera);
  const standard = near(STD_ISO, p.iso, 0.05) && near(STD_SHUTTER, p.shutter);
  if (!system || !standard) return "expert";
  const { aperture: n, shutter: t, iso } = p;
  const textbook =
    (t >= 1 && n >= 5.6 && iso <= 400) || // tripod long exposure: trails, silky water
    t <= 1 / 1000 || // frozen action
    (n <= 2.8 && iso <= 800 && t <= 1 / 60) || // wide open, blurry background
    (n >= 8 && iso <= 200 && t <= 1 / 60 && t >= 1 / 800); // classic daylight landscape
  return textbook ? "beginner" : "intermediate";
}

// Commons "Artist" fields are free text; boil them down to a name.
function cleanAuthor(a = "") {
  a = a.replace(/~commonswiki/g, "").trim();
  const assumed = a.match(/No machine-readable author provided\.\s*(.+?) assumed/);
  if (assumed) return assumed[1];
  const byMe = a.match(/by me,\s*([^(.,]+)/i) || a.match(/by its author,\s*([^.]+)/i);
  if (byMe) return byMe[1].trim();
  return a.length > 60 ? a.slice(0, 57).trim() + "…" : a || "Unknown";
}

function cleanCamera(c) {
  if (!c) return null;
  return c.replace(/^(\w+)( CORPORATION| COMPANY| IMAGING CORP\.)?\s+\1\s*/i, "$1 ").replace(/\s+/g, " ").trim();
}

const photos = candidates
  .filter((p) => !exclude.has(p.id))
  .map((p) => ({
    id: p.id,
    level: forced.get(p.id) ?? autoLevel(p),
    title: p.title,
    image: p.image.split("?")[0],
    source: p.source,
    author: cleanAuthor(p.author),
    license: p.license,
    camera: cleanCamera(p.camera),
    focalLength: p.focalLength,
    aperture: p.aperture,
    shutter: p.shutter,
    iso: p.iso,
  }))
  .concat(
    mine
      .filter((p) => !exclude.has(p.id))
      .map((p) => ({
        id: p.id,
        level: forced.get(p.id) ?? autoLevel(p),
        mine: true,
        title: p.title,
        image: p.image,
        source: null,
        author: p.author,
        license: null,
        camera: cleanCamera(p.camera),
        focalLength: p.focalLength,
        aperture: p.aperture,
        shutter: p.shutter,
        iso: p.iso,
      }))
  );

const count = (l) => photos.filter((p) => p.level === l).length;
const js =
  "// Generated by tools/build-photo-data.mjs. Do not edit by hand.\n" +
  "// Public domain / CC0 photos from Wikimedia Commons with their original EXIF settings.\n" +
  "window.PHOTOS = " + JSON.stringify(photos, null, 1) + ";\n";

await writeFile(new URL("../data/photos.js", import.meta.url), js);
console.log(`Wrote ${photos.length} photos: beginner ${count("beginner")}, intermediate ${count("intermediate")}, expert ${count("expert")}`);
